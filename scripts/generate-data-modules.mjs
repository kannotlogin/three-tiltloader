// scripts/generate-data-modules.mjs
// Wraps the existing generated JSON databases into plain ES module data files.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dataDir = path.join(__dirname, '..', 'src', 'data');

const targets = [
    { json: 'brush-database.json', out: 'brush-database.generated.js', name: 'BRUSH_DATABASE' },
    { json: 'environment-database.json', out: 'environment-database.generated.js', name: 'ENVIRONMENT_DATABASE' },
    { json: 'cubemap-database.json', out: 'cubemap-database.generated.js', name: 'CUBEMAP_DATABASE' },
    { json: 'script-guid-map.json', out: 'script-guid-map.generated.js', name: 'SCRIPT_GUID_MAP' },
];

for (const { json, out, name } of targets) {
    const data = JSON.parse(readFileSync(path.join(dataDir, json), 'utf8'));
    const banner =
        `// Generated by scripts/generate-data-modules.mjs from data/${json}.\n` +
        `// Do not edit by hand -- re-run the generator instead.\n\n`;
    const body = `export const ${name} = ${JSON.stringify(data, null, 2)};\n`;
    writeFileSync(path.join(dataDir, out), banner + body);
    console.log(`wrote ${out}`);
}
